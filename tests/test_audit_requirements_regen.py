"""Exercise trusted offline audit regeneration without GitHub or network access."""

import json
import os
import re
import shutil
import subprocess  # nosec B404 - fixed shell entry point with offline command shims
from pathlib import Path

import pytest
import yaml
from assertpy import assert_that

ROOT = Path(__file__).resolve().parents[1]
HEADER = "# Generated by scripts/export-audit-requirements.sh; do not edit.\n"


@pytest.fixture
def regeneration_repo(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """Copy trusted entry points and install data-only Git/uv shims."""
    scripts = tmp_path / "scripts"
    (scripts / "ci").mkdir(parents=True)
    for name in ("export-audit-requirements.sh", "ci/audit_requirements_regen.sh"):
        shutil.copy2(src=ROOT / "scripts" / name, dst=scripts / name)
    head = tmp_path / "head-data"
    head.mkdir()
    for name in ("pyproject.toml", "uv.lock"):
        (head / name).write_text(f"updated {name}\n", encoding="utf-8")
        (tmp_path / name).write_text("trusted base\n", encoding="utf-8")
    (head / "requirements-audit.txt").write_text(
        HEADER + "example==1.0\n",
        encoding="utf-8",
    )
    (tmp_path / "requirements-audit.txt").write_text("base\n", encoding="utf-8")
    mock_bin = tmp_path / "bin"
    mock_bin.mkdir()
    commands = {
        "git": (
            'printf "%s\\n" "$*" >> "$AUDIT_GIT_CALLS"\n'
            'case "$1" in\n'
            'fetch) exit "${AUDIT_FETCH_EXIT:-0}" ;;\n'
            'show) cat "$AUDIT_HEAD_DATA/${2#*:}" ;;\n'
            "*) exit 90 ;;\nesac\n"
        ),
        "uv": (
            '[[ "$*" == "export --locked --offline --all-groups '
            '--no-emit-project --no-hashes --no-header --no-annotate" ]]\n'
            'cmp pyproject.toml "$AUDIT_HEAD_DATA/pyproject.toml"\n'
            'cmp uv.lock "$AUDIT_HEAD_DATA/uv.lock"\n'
            'echo "example==${AUDIT_VERSION:-2.0}"\n'
            'exit "${AUDIT_EXPORT_EXIT:-0}"\n'
        ),
    }
    for name, body in commands.items():
        command = mock_bin / name
        command.write_text("#!/usr/bin/env bash\nset -euo pipefail\n" + body)
        command.chmod(0o755)
    monkeypatch.setenv("PATH", f"{mock_bin}{os.pathsep}{os.environ['PATH']}")
    monkeypatch.setenv("PR_HEAD_SHA", "a" * 40)
    monkeypatch.setenv("AUDIT_HEAD_DATA", str(head))
    monkeypatch.setenv("AUDIT_GIT_CALLS", str(tmp_path / "git-calls"))
    monkeypatch.setenv("GITHUB_OUTPUT", str(tmp_path / "output"))
    return scripts / "ci" / "audit_requirements_regen.sh"


@pytest.mark.parametrize(
    ("setting", "value", "expected_code", "expected_output"),
    [
        ("AUDIT_VERSION", "2.0", 0, "changed=true\n"),
        ("AUDIT_VERSION", "1.0", 0, "changed=false\n"),
        ("AUDIT_EXPORT_EXIT", "7", 7, ""),
        ("AUDIT_FETCH_EXIT", "8", 8, ""),
        ("PR_HEAD_SHA", "--upload-pack=bad", 2, ""),
    ],
    ids=["updated", "already-current", "export-fails", "fetch-fails", "bad-head"],
)
def test_regeneration_boundary(
    regeneration_repo: Path,
    monkeypatch: pytest.MonkeyPatch,
    setting: str,
    value: str,
    expected_code: int,
    expected_output: str,
) -> None:
    """Only publish after exact-head data export and freshness verification."""
    root = regeneration_repo.parents[2]
    monkeypatch.setenv(setting, value)
    result = subprocess.run(  # nosec B603 B607 - fixed bash argv, no network
        ["bash", str(regeneration_repo)],
        cwd=root,
        capture_output=True,
        text=True,
        check=False,
    )
    assert_that(result.returncode).described_as(result.stderr).is_equal_to(
        expected_code
    )
    output = root / "output"
    assert_that(output.read_text() if output.exists() else "").is_equal_to(
        expected_output
    )
    if expected_code:
        assert_that((root / "requirements-audit.txt").read_text()).is_equal_to("base\n")
    else:
        assert_that((root / "requirements-audit.txt").read_text()).is_equal_to(
            HEADER + f"example=={value}\n",
        )
        calls = (root / "git-calls").read_text()
        assert_that(calls).contains(f"show {'a' * 40}:uv.lock")
        assert_that(calls).does_not_contain("scripts/", "commit", "push")


def test_renovate_exclusion_is_only_generated_root_audit_file() -> None:
    """Keep other requirements and managers eligible for dependency updates."""
    config = json.loads((ROOT / "renovate.json").read_text())
    rules = [rule for rule in config["packageRules"] if rule.get("enabled") is False]
    assert_that(rules).is_length(1)
    rule = rules[0]
    assert_that(rule["matchManagers"]).is_equal_to(["pip_requirements"])
    (pattern,) = rule["matchFileNames"]
    regex = re.compile(pattern[1:-1])
    for name, matches in (
        ("requirements-audit.txt", True),
        ("requirements.txt", False),
        ("requirements-dev.txt", False),
        ("sub/requirements-audit.txt", False),
        ("requirements-audit.txt.backup", False),
    ):
        assert_that(bool(regex.search(name))).described_as(name).is_equal_to(matches)


def test_regeneration_workflow_uses_trusted_code_and_signed_append() -> None:
    """Keep PR data separate from the trusted workflow and App write boundary."""
    workflow = yaml.safe_load(
        (ROOT / ".github/workflows/audit-requirements-regen.yml").read_text(),
    )
    job = workflow["jobs"]["regenerate"]
    assert_that(job["permissions"]).is_equal_to({"contents": "read"})
    assert_that(job["if"]).contains(
        "github.repository == 'lgtm-hq/ai-skills'",
        "github.event.pull_request.user.login == 'renovate[bot]'",
        "github.event.pull_request.head.repo.full_name == github.repository",
        "github.triggering_actor",
    )
    steps = job["steps"]
    checkout = next(
        step for step in steps if "actions/checkout@" in step.get("uses", "")
    )
    assert_that(checkout["with"]["ref"]).is_equal_to(
        "${{ github.event.pull_request.base.sha }}"
    )
    assert_that(checkout["with"]["persist-credentials"]).is_false()
    signer = next(
        step for step in steps if "create-signed-commit@" in step.get("uses", "")
    )
    assert_that(signer["with"]["files"].strip()).is_equal_to("requirements-audit.txt")
    assert_that(signer["with"]["mode"]).is_equal_to("append")
    assert_that(signer["with"]["expected-head"]).is_equal_to(
        "${{ github.event.pull_request.head.sha }}"
    )
    assert_that(signer["if"]).contains("steps.regenerate.outputs.changed == 'true'")
