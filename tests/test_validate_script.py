@pytest.mark.parametrize(
    ("case", "expected_status", "expected_output"),
    [
        ("matching", 0, "Validation passed."),
        ("stale", 1, "Validation failed with 1 error(s)."),
        ("export-failure", 1, "Mock export failed"),
        ("missing-helper", 1, "export-audit-requirements.sh"),
        ("missing-requirements", 1, "requirements-audit.txt"),
    ],
)
def test_validate_audit_export(
    audit_validation_repo: Path,
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    case: str,
    expected_status: int,
    expected_output: str,
) -> None:
    """Validate freshness and fail closed at the real shell entry point."""
    requirements = tmp_path / "requirements-audit.txt"
    if case == "stale":
        requirements.write_text("example==0.9\n", encoding="utf-8")
    elif case == "export-failure":
        monkeypatch.setenv("AUDIT_EXPORT_FAIL", "1")
    elif case == "missing-helper":
        audit_validation_repo.with_name("export-audit-requirements.sh").unlink()
    elif case == "missing-requirements":
        requirements.unlink()
    committed_export = requirements.read_bytes() if requirements.exists() else None

    result = _run_validate(script_path=audit_validation_repo, cwd=tmp_path)

    assert_that(result.returncode).is_equal_to(expected_status)
    assert_that(result.stdout + result.stderr).contains(expected_output)
    if expected_status:
        assert_that(result.stdout).contains("Validation failed with 1 error(s).")
    if case != "missing-helper":
        assert_that((tmp_path / "uv-calls.txt").read_text()).contains("export ")
    if committed_export is not None:
        assert_that(requirements.read_bytes()).is_equal_to(committed_export)
    else:
        assert_that(requirements.exists()).is_false()


