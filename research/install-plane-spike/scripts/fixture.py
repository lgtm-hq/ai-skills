#!/usr/bin/env python3
"""Generate or check the tiny deterministic, data-only USTAR golden artifact."""

from __future__ import annotations

import argparse
import hashlib
import io
import json
import tarfile
from pathlib import Path

FIXTURE = Path(__file__).resolve().parents[1] / "fixtures"


def generate() -> dict[str, bytes]:
    """Build canonical fixture bytes in memory.

    Returns:
        Filename to generated bytes, including the expected retained contents.
    """
    contents = {
        "keep/SKILL.md": "# Keep\n\nA retained fixture capability.\n",
        "drop/SKILL.md": "# Drop\n\nAn excluded fixture capability.\n",
    }
    buffer = io.BytesIO()
    with tarfile.open(fileobj=buffer, mode="w", format=tarfile.USTAR_FORMAT) as archive:
        for name, content in sorted(contents.items()):
            payload = content.encode()
            member = tarfile.TarInfo(name)
            member.size = len(payload)
            member.mode = 0o644
            archive.addfile(tarinfo=member, fileobj=io.BytesIO(payload))
    payload = buffer.getvalue()
    index = {
        "sha256": hashlib.sha256(payload).hexdigest(),
        "capabilities": [
            {
                "id": f"fixture:{name.split('/')[0]}",
                "closure": [],
                "files": {name: hashlib.sha256(content.encode()).hexdigest()},
            }
            for name, content in sorted(contents.items())
        ],
    }
    return {
        "artifact.tar": payload,
        "index.json": (json.dumps(index, indent=2) + "\n").encode(),
        "expected-output.json": (
            json.dumps({"keep/SKILL.md": contents["keep/SKILL.md"]}, indent=2) + "\n"
        ).encode(),
    }


def main() -> int:
    """Write the fixture, or fail on byte drift without changing files.

    Returns:
        Zero for a generated/current fixture; one for drift.
    """
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, payload in generate().items():
        path = FIXTURE / name
        if args.check:
            if not path.exists() or path.read_bytes() != payload:
                print(f"fixture drift: {path}")
                return 1
        else:
            path.write_bytes(payload)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
