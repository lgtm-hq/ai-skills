#!/usr/bin/env bash
# Generate lintro's pip_audit input from the locked dev dependencies, offline.
set -euo pipefail

repo_dir=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
cd "$repo_dir"
audit_tmp=$(mktemp)
trap 'rm -f "$audit_tmp"' EXIT

{
  echo '# Generated by scripts/export-audit-requirements.sh; do not edit.'
  uv export --locked --offline --all-groups --no-emit-project \
    --no-hashes --no-header --no-annotate
} >"$audit_tmp"

case "${1:-}" in
--check)
  diff -u requirements-audit.txt "$audit_tmp"
  ;;
'')
  cp "$audit_tmp" requirements-audit.txt
  ;;
*)
  echo 'Usage: bash scripts/export-audit-requirements.sh [--check]' >&2
  exit 2
  ;;
esac
