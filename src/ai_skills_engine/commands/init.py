"""``ai-skills-engine init``: scaffold ``ai-skills.yaml`` and a caller workflow.

Detects ``skills/*/SKILL.md``, ``agents/*.md`` and existing ``.claude-plugin`` or
``.cursor-plugin`` manifests, then proposes ``packages:`` with qualified IDs and
explicit ``exports:``. Existing files are never overwritten: a second run is a
no-op that reports them. ``--dry-run`` prints instead of writing.

The caller workflow pins the reusable ``ai-skills-validate.yml`` workflow and
the engine by the same full 40-hex commit SHA: ``--engine-ref`` or, when
omitted, the SHA of this engine's release tag resolved from GitHub.
"""

import argparse
import json
import os
import re
import sys
from pathlib import Path
from typing import Any

from ai_skills_engine.artifact import installed_engine_version
from ai_skills_engine.commands.mapping_scaffold import kebab
from ai_skills_engine.manifest.edit import dump_document
from ai_skills_engine.manifest.identity import SEGMENT
from ai_skills_engine.manifest.validate import validate_document

ENGINE_REPO = "lgtm-hq/ai-skills"
REUSABLE_WORKFLOW = ".github/workflows/ai-skills-validate.yml"
CALLER_WORKFLOW = ".github/workflows/ai-skills.yml"
_SHA = re.compile(r"[0-9a-f]{40}")
_REMOTE = re.compile(
    r"github\.com[:/](?P<owner>[A-Za-z0-9_.-]+)/(?P<name>[A-Za-z0-9_.-]+?)(?:\.git)?/?$"
)
_HOST_MANIFESTS = (".claude-plugin", ".cursor-plugin")
_MANIFEST_HEADER = (
    "# Generated by ai-skills-engine init; review the proposed packages and\n"
    "# exports, then run `ai-skills-engine validate`.\n"
)
_CALLER = """---
# Generated by ai-skills-engine init. Calls the reusable ai-skills workflow;
# both the workflow and the engine are pinned to one immutable commit.
name: ai-skills

'on':
  pull_request:
  push:
    branches: [main]

permissions:
  contents: read

jobs:
  validate:
    name: Validate ai-skills manifest
    permissions:
      contents: read
    # yamllint disable-line rule:line-length
    uses: {repo}/{workflow}@{sha} # ai-skills {version}
    with:
      engine-ref: '{sha}'
      manifest-path: ai-skills.yaml
      strict: true
"""


def resolve_engine_ref(version: str) -> str:
    """Resolve this engine's release tag to its commit SHA on GitHub.

    Args:
        version: Installed engine version.

    Returns:
        40-hex commit SHA.

    Raises:
        ValueError: For development builds without a release tag.
    """
    if not re.fullmatch(r"\d+\.\d+\.\d+", version):
        raise ValueError(f"engine {version} has no release tag; pass --engine-ref SHA")
    from ai_skills_engine.registry.vendor import Vendor
    from ai_skills_engine.vendors.repin import resolve_upstream_sha

    return resolve_upstream_sha(
        vendor=Vendor(
            id="ai-skills",
            repo=ENGINE_REPO,
            sha="0" * 40,
            skill_roots=(),
            license="",
            homepage="",
            display_ref=f"v{version}",
        )
    )


def caller_workflow(*, sha: str, version: str) -> str:
    """Render the caller workflow pinned to one engine commit.

    Args:
        sha: Full 40-hex engine commit.
        version: Engine version recorded as a comment.

    Returns:
        Workflow YAML.

    Raises:
        ValueError: If ``sha`` is not a full lowercase commit SHA.
    """
    if not _SHA.fullmatch(sha):
        raise ValueError(f"--engine-ref must be a full 40-hex commit SHA: {sha!r}")
    return _CALLER.format(
        repo=ENGINE_REPO, workflow=REUSABLE_WORKFLOW, sha=sha, version=version
    )


def _origin(root: Path) -> tuple[str, str] | None:
    """Read the GitHub ``origin`` remote from ``.git/config`` text, never git itself.

    Args:
        root: Repository root.

    Returns:
        Owner and repository name, when declared.
    """
    config = root / ".git" / "config"
    if not config.is_file() or config.is_symlink():
        return None
    section = ""
    for line in config.read_text(encoding="utf-8", errors="replace").splitlines():
        stripped = line.strip()
        if stripped.startswith("["):
            section = stripped
        elif section == '[remote "origin"]' and stripped.startswith("url"):
            match = _REMOTE.search(stripped.partition("=")[2].strip())
            if match:
                return match["owner"], match["name"]
    return None


def _plugin_metadata(root: Path) -> dict[str, str]:
    """Read the first existing host plugin manifest's name and description.

    Args:
        root: Repository root.

    Returns:
        ``name``/``description`` strings that were present.
    """
    for directory in _HOST_MANIFESTS:
        path = root / directory / "plugin.json"
        if not path.is_file() or path.is_symlink():
            continue
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (UnicodeDecodeError, ValueError):
            continue
        if isinstance(data, dict):
            return {
                key: value
                for key in ("name", "description")
                if isinstance(value := data.get(key), str) and value.strip()
            }
    return {}


def _capabilities(root: Path, notes: list[str]) -> list[dict[str, Any]]:
    """Propose capabilities for top-level skills and agents.

    Args:
        root: Repository root.
        notes: Receives skipped-path explanations.

    Returns:
        Capability declarations in path order.
    """
    found: list[dict[str, Any]] = []
    candidates = [
        (path.parent, "skill") for path in (root / "skills").glob("*/SKILL.md")
    ] + [(path, "specialist") for path in (root / "agents").glob("*.md")]
    for path, role in sorted(candidates):
        relative = path.relative_to(root).as_posix()
        name = path.stem if role == "specialist" else path.name
        if path.is_symlink() or (path / "SKILL.md").is_symlink():
            notes.append(f"skipped {relative}: symbolic links are not published")
        elif not re.fullmatch(SEGMENT, name):
            notes.append(f"skipped {relative}: {name!r} is not a kebab-case ID")
        else:
            found.append(
                {"id": name, "path": relative}
                | ({"role": role} if role != "skill" else {})
            )
    return found


def propose(
    *, root: Path, publisher: str | None, repo: str | None
) -> tuple[dict[str, Any], list[str]]:
    """Build a manifest proposal from repository layout only.

    Args:
        root: Repository root.
        publisher: Explicit publisher ID.
        repo: Explicit ``owner/name``.

    Returns:
        Manifest document and human-readable notes.

    Raises:
        ValueError: If nothing publishable is found or IDs are invalid.
    """
    notes = [
        f"{directory}/marketplace.json exists; `ai-skills-engine generate` owns "
        "host marketplaces and `validate` checks them for drift"
        for directory in _HOST_MANIFESTS
        if (root / directory / "marketplace.json").exists()
    ]
    origin = tuple(repo.split("/", 1)) if repo else _origin(root)
    publisher_id = publisher or kebab(origin[0] if origin else root.name)
    metadata = _plugin_metadata(root)
    package_id = kebab(metadata.get("name") or (origin[1] if origin else root.name))
    capabilities = _capabilities(root, notes)
    if not capabilities:
        raise ValueError(
            "no skills/*/SKILL.md or agents/*.md found; nothing to publish"
        )
    package: dict[str, Any] = {"id": package_id}
    if "name" in metadata:
        package["name"] = metadata["name"]
    if "description" in metadata:
        package["description"] = metadata["description"]
    package["capabilities"] = capabilities
    document: dict[str, Any] = {
        "apiVersion": "ai-skills.dev/v1",
        "publisher": {"id": publisher_id}
        | ({"repo": "/".join(origin)} if origin else {}),
        "packages": [package],
        "exports": [package_id],
    }
    errors = validate_document(document)
    if errors:
        raise ValueError(
            "proposed manifest is invalid; pass --publisher/--repo: "
            + "; ".join(f"{item.location}: {item.message}" for item in errors)
        )
    return document, notes


def _create(path: Path, text: str) -> bool:
    """Create a file exclusively, never replacing an existing one.

    Args:
        path: Destination.
        text: Contents.

    Returns:
        Whether the file was created; False if it already existed.
    """
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        descriptor = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o644)
    except FileExistsError:
        return False
    with os.fdopen(descriptor, "w", encoding="utf-8") as handle:
        handle.write(text)
    return True


def main(argv: list[str] | None = None) -> int:
    """Scaffold a publishing manifest and caller workflow without overwriting.

    Args:
        argv: Command arguments.

    Returns:
        Zero on success or when files already exist; one on errors.
    """
    parser = argparse.ArgumentParser(prog="ai-skills-engine init", description=__doc__)
    parser.add_argument("--repo-root", type=Path, help="Default: current directory")
    parser.add_argument("--dry-run", action="store_true", help="Print, write nothing")
    parser.add_argument("--publisher", help="Publisher ID (default: repository owner)")
    parser.add_argument("--repo", help="Publisher repository as OWNER/NAME")
    parser.add_argument(
        "--engine-ref",
        help="Full 40-hex ai-skills commit for the workflow pin "
        "(default: this engine's release tag)",
    )
    args = parser.parse_args(argv)
    root = (args.repo_root or Path.cwd()).resolve()
    manifest = root / "ai-skills.yaml"
    workflow = root / CALLER_WORKFLOW
    try:
        if args.repo is not None and not re.fullmatch(
            r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", args.repo
        ):
            raise ValueError(f"--repo must be OWNER/NAME: {args.repo!r}")
        files: dict[Path, str] = {}
        if manifest.exists(follow_symlinks=False):
            print(f"init: {manifest.name} already exists; left unchanged")
        else:
            document, notes = propose(
                root=root, publisher=args.publisher, repo=args.repo
            )
            for note in notes:
                print(f"init: {note}", file=sys.stderr)
            files[manifest] = _MANIFEST_HEADER + dump_document(document)
        if workflow.exists(follow_symlinks=False):
            print(f"init: {CALLER_WORKFLOW} already exists; left unchanged")
        else:
            version = installed_engine_version()
            sha = args.engine_ref or resolve_engine_ref(version)
            files[workflow] = caller_workflow(sha=sha, version=version)
    except (OSError, RuntimeError, TypeError, ValueError) as error:
        print(f"init: {error}", file=sys.stderr)
        return 1
    for path, text in files.items():
        relative = path.relative_to(root).as_posix()
        if args.dry_run:
            print(f"init: would write {relative}:\n{text}", end="")
        elif _create(path, text):
            print(f"init: wrote {relative}")
        else:
            print(f"init: {relative} already exists; left unchanged")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
